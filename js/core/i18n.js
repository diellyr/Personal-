// Minimal i18n: a flat key->string dictionary per language, a t(key)
// lookup with graceful fallback to the key itself (so a missing
// translation degrades to a visible-but-ugly string, never a crash), and a
// subscription hook so the language toggle can force a full re-render —
// this app has no reactive framework, so "switching language" means
// re-invoking whatever render() built the current screen, the same way a
// route change already does.
const STORAGE_KEY = 'dielly_os_lang';
const listeners = new Set();
let currentLang = localStorage.getItem(STORAGE_KEY) === 'en' ? 'en' : 'pt';

export function getLanguage() {
  return currentLang;
}

export function setLanguage(lang) {
  if (lang !== 'pt' && lang !== 'en') return;
  if (lang === currentLang) return;
  currentLang = lang;
  localStorage.setItem(STORAGE_KEY, lang);
  listeners.forEach((fn) => fn(lang));
}

export function onLanguageChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/** t(key) looks up the current language's string; t(key, {n: 5}) does
 * simple {n} placeholder substitution for pluralized/interpolated strings. */
export function t(key, vars) {
  const dict = DICTIONARIES[currentLang] || DICTIONARIES.pt;
  let str = dict[key] ?? DICTIONARIES.pt[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => { str = str.replaceAll(`{${k}}`, v); });
  }
  return str;
}

